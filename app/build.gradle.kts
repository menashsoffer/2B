          // Preview functions are design-time UI entry points.
          annotatedBy("androidx.compose.ui.tooling.preview.Preview")
        }
        // BuildConfig is generated by Android Gradle Plugin.
        classes("*.BuildConfig")
        // Resource identifiers are generated by Android Gradle Plugin.
        classes("*.R")
